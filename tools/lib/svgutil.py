#  geometry helpers -- all outputs are closed, fillable path data
# --------------------------------------------------------------------------- #


def _arc_cubics(cx: float, cy: float, r: float, a0: float, a1: float) -> list[tuple]:
    """Circular arc -> list of cubic bezier control points.

    Angles in degrees, measured clockwise from 12 o'clock (screen convention:
    y grows downward, so we mirror sin).
    """
    sweep = a1 - a0
    if abs(sweep) < 1e-9:
        return []
    segs = max(1, int(math.ceil(abs(sweep) / 90.0)))
    step = sweep / segs
    kappa = 4.0 / 3.0 * math.tan(math.radians(step) / 4.0)

    def pt(a: float) -> tuple[float, float]:
        ra = math.radians(a)
        return (cx + r * math.sin(ra), cy - r * math.cos(ra))

    out = []
    for i in range(segs):
        a = a0 + i * step
        b = a + step
        p0, p3 = pt(a), pt(b)

        def tangent(ang: float) -> tuple[float, float]:
            ra = math.radians(ang)
            return (math.cos(ra), math.sin(ra))  # d/da of (sin, -cos)

        t0 = tangent(a)
        t3 = tangent(b)
        p1 = (p0[0] + kappa * r * t0[0], p0[1] + kappa * r * t0[1])
        p2 = (p3[0] - kappa * r * t3[0], p3[1] - kappa * r * t3[1])
        out.append((p0, p1, p2, p3))
    return out


def _arc_d(cx: float, cy: float, r: float, a0: float, a1: float, start: bool = False) -> str:
    segs = _arc_cubics(cx, cy, r, a0, a1)
    if not segs:
        return ""
    d = ""
    if start:
        d += f"M{n(segs[0][0][0])} {n(segs[0][0][1])}"
    for _, p1, p2, p3 in segs:
        d += f"C{n(p1[0])} {n(p1[1])} {n(p2[0])} {n(p2[1])} {n(p3[0])} {n(p3[1])}"
    return d


def circle_d(cx: float, cy: float, r: float) -> str:
    return _arc_d(cx, cy, r, 0, 360, start=True) + "Z"


def ring_d(cx: float, cy: float, r_out: float, r_in: float) -> str:
    """Full annulus (donut). Inner contour reversed so even-odd / non-zero both work."""
    outer = _arc_d(cx, cy, r_out, 0, 360, start=True) + "Z"
    inner = _arc_d(cx, cy, r_in, 360, 0, start=True) + "Z"
    return outer + inner


def arc_band_d(cx: float, cy: float, r_out: float, r_in: float, a0: float, a1: float) -> str:
    """Annular sector (arc band) between two radii, swept a0 -> a1 (clockwise)."""
    o = _arc_d(cx, cy, r_out, a0, a1, start=True)
    px, py = _polar(cx, cy, r_in, a1)
    inner = _arc_d(cx, cy, r_in, a1, a0, start=False)   # starts with 'C' -> safe to concat
    return f"{o}L{n(px)} {n(py)}{inner}Z"


def _polar(cx: float, cy: float, r: float, ang: float) -> tuple[float, float]:
    ra = math.radians(ang)
    return (cx + r * math.sin(ra), cy - r * math.cos(ra))


def dot_d(cx: float, cy: float, r: float) -> str:
    return circle_d(cx, cy, r)


def bar_d(x0: float, y0: float, x1: float, y1: float, w: float) -> str:
    """Filled round-capped? No: square-capped bar between two points with width w."""
    dx, dy = x1 - x0, y1 - y0
    L = math.hypot(dx, dy) or 1.0
    ux, uy = dx / L, dy / L
    px, py = -uy * w / 2.0, ux * w / 2.0
    return (
        f"M{n(x0 + px)} {n(y0 + py)}"
        f"L{n(x1 + px)} {n(y1 + py)}"
        f"L{n(x1 - px)} {n(y1 - py)}"
        f"L{n(x0 - px)} {n(y0 - py)}Z"
    )


def rect_d(x: float, y: float, w: float, h: float, r: float = 0.0) -> str:
    """Rectangle (clockwise). Only M/L/C/Z commands are emitted so that the
    production exporters never have to resolve shorthand commands."""
    if r <= 0:
        return (
            f"M{n(x)} {n(y)}L{n(x + w)} {n(y)}L{n(x + w)} {n(y + h)}"
            f"L{n(x)} {n(y + h)}Z"
        )
    r = min(r, w / 2, h / 2)
    k = r * 0.5523
    return (
        f"M{n(x + r)} {n(y)}L{n(x + w - r)} {n(y)}"
        f"C{n(x + w - r + k)} {n(y)} {n(x + w)} {n(y + r - k)} {n(x + w)} {n(y + r)}"
        f"L{n(x + w)} {n(y + h - r)}"
        f"C{n(x + w)} {n(y + h - r + k)} {n(x + w - r + k)} {n(y + h)} {n(x + w - r)} {n(y + h)}"
        f"L{n(x + r)} {n(y + h)}"
        f"C{n(x + r - k)} {n(y + h)} {n(x)} {n(y + h - r + k)} {n(x)} {n(y + h - r)}"
        f"L{n(x)} {n(y + r)}"
        f"C{n(x)} {n(y + r - k)} {n(x + r - k)} {n(y)} {n(x + r)} {n(y)}Z"
    )


def arch_contour_d(w: float, h: float, base: float = 0.0) -> str:
    """Single closed contour of a stadium 'arch portal' (squared base,
    semicircular crown).  Local space: x centred on 0, base at y=base,
    the portal grows upward (negative y).  Width w = 2*r, height h >= w/2."""
    r = w / 2.0
    shoulder = base - h + r            # centre of the crown circle
    d = f"M{n(-r)} {n(base)}L{n(-r)} {n(shoulder)}"
    d += _arc_d(0.0, shoulder, r, 270.0, 450.0)   # left -> crown -> right
    d += f"L{n(r)} {n(base)}Z"
    return d


def _arch_local(w: float, h: float, t: float, y0: float = 0.0) -> str:
    """Outline of a stadium arch portal of wall thickness t (ring-like, filled)."""
    return arch_contour_d(w, h, y0) + arch_contour_d(w - 2 * t, h - t, y0)


def arcade_band_d(
    cx: float,
    cy: float,
    r_in: float,
    r_out: float,
    count: int,
    hole_w: float,
    hole_h: float,
    *,
    hole_base: float | None = None,
    skip: tuple[float, ...] = (),
    skip_tol: float = 0.0,
) -> str:
    """Colosseum arcade seen from above: an annular band with `count` arched
    openings knocked out of it (fill with rule='evenodd')."""
    from .pathparse import transform_d

    d = ring_d(cx, cy, r_out, r_in)
    base = r_in if hole_base is None else hole_base
    for i in range(count):
        a = i * 360.0 / count
        if skip and min(abs(((a - s + 180.0) % 360.0) - 180.0) for s in skip) <= skip_tol:
            continue
        px, py = _polar(cx, cy, base, a)
        rad = math.radians(a)
        ca, sa = math.cos(rad), math.sin(rad)
        d += transform_d(arch_contour_d(hole_w, hole_h), (ca, sa, -sa, ca, px, py))
    return d


@dataclass
class Place:
    """2D affine placement for local-space geometry."""

    x: float = 0.0
    y: float = 0.0
    rot: float = 0.0  # degrees, clockwise (screen)
    scale: float = 1.0

    def pt(self, px: float, py: float) -> tuple[float, float]:
        a = math.radians(self.rot)
        ca, sa = math.cos(a), math.sin(a)
        sx, sy = px * self.scale, py * self.scale
        return (self.x + sx * ca - sy * sa, self.y + sx * sa + sy * ca)


