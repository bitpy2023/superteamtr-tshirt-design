class Shaper:
    """HarfBuzz shaping + fontTools outlines. Optionally instantiate a weight."""

    def __init__(self, font_path: str, weight: float | None = None, cache_key: str = ""):
        self.font_path = font_path
        self.weight = weight
        raw = open(font_path, "rb").read()
        self.tt = TTFont(font_path)
        if weight is not None and "fvar" in self.tt:
            self.tt = instantiateVariableFont(self.tt, {"wght": float(weight)})
        self.glyph_set = self.tt.getGlyphSet()
        self.upem = self.tt["head"].unitsPerEm
        self.order = self.tt.getGlyphOrder()
        self.hbfont = hb.Font(hb.Face(raw))
        if weight is not None:
            self.hbfont.set_variations({"wght": float(weight)})

    # -- shaping ---------------------------------------------------------- #
    def glyphs(self, text: str, size: float, tracking: float = 0.0):
        """Return [(gid, x, y, advance)] in mm units at the requested size."""
        buf = hb.Buffer()
        buf.add_str(text)
        buf.guess_segment_properties()
        hb.shape(self.hbfont, buf)
        s = size / self.upem
        out, x = [], 0.0
        for info, pos in zip(buf.glyph_infos, buf.glyph_positions):
            out.append((info.codepoint, x + pos.x_offset * s, -pos.y_offset * s, pos.x_advance * s))
            x += pos.x_advance * s + tracking
        return out, (x - tracking if out else 0.0)

    def measure(self, text: str, size: float, tracking: float = 0.0) -> float:
        return self.glyphs(text, size, tracking)[1]

    def path(
        self,
        text: str,
        size: float,
        *,
        x: float = 0.0,
        baseline: float = 0.0,
        tracking: float = 0.0,
        anchor: str = "start",
    ) -> tuple[str, float]:
        """Outlined path data (y-down) + advance width."""
        gly, width = self.glyphs(text, size, tracking)
        if anchor == "middle":
            x -= width / 2.0
        elif anchor == "end":
            x -= width
        s = size / self.upem
        chunks = []
        for gid, gx, gy, _adv in gly:
            name = self.order[gid]
            pen = SVGPathPen(self.glyph_set)
            # font units -> mm, with a y-flip because font design space is y-up
            tpen = TransformPen(pen, Transform(s, 0, 0, -s, x + gx, baseline + gy))
            self.glyph_set[name].draw(tpen)
            d = pen.getCommands()
            if d:
                chunks.append(d)
        return (" ".join(chunks), width)

    def circular_path(
        self,
        text: str,
        *,
        cx: float,
        cy: float,
        radius: float,
        size: float,
        tracking: float = 0.0,
        start_angle: float = 0.0,
        direction: int = 1,
        flip: bool = False,
    ) -> str:
        """Text set around a circle (angles clockwise from 12 o'clock)."""
        gly, width = self.glyphs(text, size, tracking)
        ang0 = start_angle - (width / radius) * (180.0 / math.pi) / 2.0 * direction
        s = size / self.upem
        chunks = []
        for gid, gx, gy, _adv in gly:
            name = self.order[gid]
            # angle on the circle for this glyph's origin
            frac = gx / radius * (180.0 / math.pi) * direction
            ang = ang0 + frac
            px, py = _polar(cx, cy, radius, ang)
            rot = ang + (180.0 if flip else 0.0)
            a = math.radians(rot)
            ca, sa = math.cos(a), math.sin(a)
            pen = SVGPathPen(self.glyph_set)
            # font space is y-up, the artwork is y-down: mirror y, then rotate
            # clockwise by `rot` so glyph tops face outwards (or inwards when flipped)
            tpen = TransformPen(
                pen,
                Transform(s * ca, s * sa, s * sa, -s * ca, px, py),
            )
            self.glyph_set[name].draw(tpen)
            d = pen.getCommands()
            if d:
                chunks.append(d)
        return " ".join(chunks)


