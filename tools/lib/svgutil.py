@dataclass
class Doc:
    """Minimal SVG document builder (y grows downward, units = mm)."""

    width: float
    height: float
    body: list[str] = field(default_factory=list)
    defs: list[str] = field(default_factory=list)
    _counter: int = 0

    def uid(self, stem: str = "id") -> str:
        self._counter += 1
        return f"{stem}_{self._counter}"

    def add(self, markup: str) -> None:
        self.body.append(markup)

    def add_def(self, markup: str) -> None:
        self.defs.append(markup)

    trace: list = field(default_factory=list)   # logo placement provenance
    fonts: list = field(default_factory=list)   # font files used (outlined)
    ink_note: str = ""
    color_map: dict = None          # optional {hex -> hex} ink remap (1-colour builds)
    gradient_mode: str = "keep"     # keep | flat | hard2
    gradient_colors: tuple = ()     # colours for flat / hard2 modes

    def ink(self, color: str) -> str:
        if self.color_map:
            return self.color_map.get(color.lower(), self.color_map.get(color, color))
        return color

    def path(self, d: str, fill: str, *, opacity: float = 1.0, rule: str = "evenodd") -> None:
        op = "" if opacity >= 0.999 else f' fill-opacity="{opacity:.3f}"'
        self.add(
            f'<path d="{d}" fill="{self.ink(fill)}" fill-rule="{rule}"{op}/>'
        )

    def group(self, markup: str, attrs: str = "") -> None:
        self.add(f"<g {attrs}>{markup}</g>")

    def header_comment(self) -> str:
        """Provenance block embedded in the SVG so the printer can audit the file."""
        import hashlib
        lines = ["<!--",
                 "  SuperteamTR T-Shirt artwork - generated by tools/build_artwork.py",
                 f"  print size: {self.width:g} x {self.height:g} mm (1 SVG unit = 1 mm)",
                 "  all visible type is converted to outlines (no fonts required)",
                 ]
        if self.fonts:
            lines.append("  typefaces used (outlined): " + ", ".join(sorted(set(self.fonts))))
        if self.ink_note:
            lines.append("  inks: " + self.ink_note)
        if self.trace:
            lines.append("  official brand assets embedded (unmodified, rigid transform):")
            for t in self.trace:
                lines.append(
                    f"    - {t['asset']}  sha256:{t['sha256']}  "
                    f"placed {t['width']:.1f} x {t['height']:.1f} mm at "
                    f"({t['x']:.1f}, {t['y']:.1f})  mode={t['mode']}")
        lines.append("-->")
        return "\n".join(lines)

    def svg(self, bg: str | None = None) -> str:
        defs = ""
        if self.defs:
            defs = "<defs>" + "".join(self.defs) + "</defs>"
        back = ""
        if bg:
            back = f'<rect x="0" y="0" width="{self.width:g}" height="{self.height:g}" fill="{bg}"/>'
        return (
            f'<svg xmlns="{SVG_NS}" xmlns:xlink="http://www.w3.org/1999/xlink" '
            f'width="{self.width:g}mm" height="{self.height:g}mm" '
            f'viewBox="0 0 {self.width:g} {self.height:g}">\n'
            f"{self.header_comment()}\n{defs}\n{back}\n" + "\n".join(self.body) + "\n</svg>\n"
        )


