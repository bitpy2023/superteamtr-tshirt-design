"""
svgutil.py -- small vector toolkit for the SuperteamTR T-Shirt design package.

Everything the artwork generator needs:
  * a tiny SVG document builder
  * geometry helpers (circles / rings / arcs / rounded "arch" portals) that emit
    FILLED paths only (no strokes) -> 100% screen-print safe, easy separations
  * text -> outline paths via HarfBuzz shaping + fontTools glyph outlines
  * official brand SVG import (paths + transforms + gradients) so the supplied
    logo files are used unmodified
"""
